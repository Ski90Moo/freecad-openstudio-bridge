"""Tests for what an elevation sketch hangs off.

Run under the bridge venv:

    osvenv/Scripts/python.exe -m unittest discover -s tests -v

These sketches used to attach to the largest imported wall face with MapMode
FlatFace.  That reads well -- the sketch plane *is* the wall -- and it is a
trap, because `import` replaces a surface's Shape outright and FlatFace then
re-derives the frame from a new face whose parametrisation need not match the
old one.  Measured: re-importing after a roof change turned three sketches
through 180 degrees and slid them up to 39 m, dragging 20 of 27 drawn outlines
into positions nobody drew, with nothing downstream to question it.

So the sketch now stands on the traced wall centerline instead, and the plan
is not regenerated by anything.  What is worth pinning down here is the
choice of line: the right one, from the right storey, and a refusal rather
than a guess when the plan cannot supply it -- ThreePointsNormal needs a third
point off the line, and three collinear points raise rather than return a bad
plane.
"""

