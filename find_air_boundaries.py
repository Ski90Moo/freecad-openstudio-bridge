"""Find air-boundary surfaces and size their air exchange from the opening.

Run under the bridge venv (system Python 3.12 + openstudio 3.11.0):

    osvenv/Scripts/python.exe find_air_boundaries.py \
        runs/mybuilding.osm \
        runs/floorplans/mybuilding.json

Prints a report and the exact `assign_air_boundary_construction` arguments to
apply.  --apply-json emits those as JSON instead, for piping.

Four rules, all stated in terms of the floor plan rather than the built model:

1.  **A shaft.** Two rooms on different stories with the *same* footprint --
    a stair, a lift shaft, a duct riser -- are one continuous volume that the
    bridge is forced to model as one space per story.  Their shared
    floor/ceiling is not a real construction, so it gets an air boundary.

2.  **A mezzanine edge.** A wall between a mezzanine and a space that spans
    more than its own story (one carrying an OS_Height override) is a
    guardrail, not a wall.

3.  **A corridor cross-section.** A wall that slices a corridor square across
    its run is a modelling division, not a construction -- the corridor is one
    continuous volume and the plan cut it into spaces.  The test is the one
    that reads off the drawing, that the wall is narrow compared with the
    length of the hallway, plus two guards that stop it firing on the
    corridor's long side.  See "Corridors" below.

4.  **An open stair edge.** A stair labelled "Open Stair" is a corridor stood
    on end.  Its long SIDES, where they face a space spanning storeys or a
    mezzanine, are guardrail edges and are taken.  Its ENDS are not: one per
    storey is the way in and the other is the wall behind the flight, and the
    plan does not carry the arrow that says which.  A plain "Stair" is
    assumed enclosed and gets nothing.

Why not read the footprints back out of the .osm: intersectSurfaces splits a
mezzanine's floor into one fragment per room beneath it, and a fragment can
coincide exactly with the small room below it.  Four such coincidences show up
in FloorplanTest-02 -- 203 RR under 205 Mezzanine among them -- and every one
of them would be a false shaft.  The exported JSON holds whole rooms, before
any splitting, so it cannot make that mistake.

Surface names are regenerated by every full build, so this is re-run after one
rather than its output being kept.  An incremental update_osm_geometry.py
--apply keeps the assignment on every space it does not rebuild.


Sizing the air exchange
-----------------------

EnergyPlus takes one air-change rate per Construction:AirBoundary and applies
it "using the volume of the smaller zone as the basis" (Energy+.idd, field N1
of Construction:AirBoundary).  One rate can therefore only be right for one
pair of spaces, so openings are grouped by space pair and each pair gets its
own construction.

Buoyancy drives the exchange, and the two opening orientations are different
problems:

**Vertical opening** (a mezzanine edge) -- counterflow through a tall aperture,
the Brown & Solvason result used for interzone flow in ASHRAE Fundamentals and
as the large-opening model in EnergyPlus's own AirflowNetwork:

    Q = (Cd / 3) * W * H^1.5 * sqrt(g * dT / T_mean)

**Horizontal opening** (a stair or shaft penetrating a floor) -- Rayleigh-
Taylor exchange through an aperture in a thin horizontal partition, Epstein
(1988), in the thin-plate regime that a ~0.2 m slab with a ~3 m opening sits
well inside (L/D of about 0.06, against a regime boundary at 0.15):

    Q = C_h * sqrt((g * dT / T_mean) * D^5)

Q is the one-way exchange; the same volume flows back the other way, which is
what an air change *is*, so ACH = Q * 3600 / V_smaller.

dT is NOT a free parameter here.  An air boundary is used precisely where two
zones are open to each other, and that exchange is what holds them together, so
they equilibrate: 0.5 K is the accepted working figure and the default.  A
large dT and an open boundary are mutually exclusive -- 10 K between adjacent
commercial zones means an enclosure, a cold store or a sauna, which would not
have an open boundary in the first place.  --delta-t is for an engineer's
judgement on a genuine edge case, not for exploring a range.

There is a useful consistency in this: the rates come out high, and that is
exactly why the 0.5 K premise holds.  Above roughly 10 ACH the coupling
saturates -- the zones track each other closely whatever the exact rate -- so
what the number really settles is whether the two spaces should have been one
zone, not how hard to mix them.

The coefficients are documented defaults, not measurements of this building.
The report prints all of them so they can be checked rather than taken on faith.


Corridors
---------

"Narrow compared with the length of the hallway" is the right instinct, and on
its own it is not enough: the width of a wall says nothing about which side of
the corridor it is on.  Measured on FloorplanTest-02's own hallways:

    101a Hallway, 8.58 m long x 1.65 m wide

        wall to 101  Lobby        1.65 m   w/L 0.19   <- an open end
        wall to 101b Hallway 6    1.65 m   w/L 0.19   <- an open end
        wall to 102  Office       1.29 m   w/L 0.15   <- a piece of the side

The office frontage is the *narrowest* wall on that corridor, and it is a wall.
So two more conditions come in, both saying the same thing -- that the surface
is a slice through the corridor rather than a fragment of its flank:

  * it spans the corridor's own width (w / W_corridor near 1);
  * it stands square to the corridor's run.

The three together select exactly the corridor ends here and reject the office
fragment (w/W 0.78), the restrooms off 101b (w/W 1.46), the stair alongside
101a (parallel to the run) and the shop wall on 101c.

Length and width are measured on the footprint's minimum-area bounding
rectangle rather than on x and y, because the building need not be axis-aligned
-- this one is drawn on a 45 degree north axis.

An L-junction satisfies the square-to-the-run test from only ONE of its two
corridors: where 101a ends into the flank of 101b, 101a sees a cross-section
and 101b sees a piece of its own side.  Each pair is therefore tested from both
corridors and taken if either agrees.  Surfaces already claimed by rule 1 or 2
are left alone.

Two cross-sections in the SAME plane, open to rooms on DIFFERENT storeys, are
rejected outright.  101c is two stories tall and ends against office 107 below
and IT room 116 above; if both were open a person would step out of 116 into
the void over the corridor.  In real construction the upper one is a guardrail
over a wall below, or there is no upper opening at all -- either way it is a
special case, so neither is assigned and both are named in the report.  If the
upper one really is a guardrail, the way to say so already exists: label that
upper room a mezzanine and rule 2 takes its edge.

Note this applies only ACROSS the run.  A long side open at two storeys is an
ordinary double-height edge, which is exactly what rule 4 relies on.

What no rule can settle: a corridor that dead-ends into a room on one storey
looks exactly like one that opens into a lobby.  Pairs whose far side is not
itself circulation or open floor are selected and then called out by name for
review.  Only the engineer can separate them, and --corridor-exclude drops the
ones that are really walls.


Open stairs
-----------

A stair is a corridor stood on end, and it inherits the corridor problem in a
sharper form.  101d's stair is 5.75 x 1.58 m, stacked over two storeys:

                     x = 6.05          long sides          x = 11.80
    Level 1 Stair    -> 101a Hallway   -> Lobby, 108 Conf   -> Lobby
    Level 2 Stair 2  -> 113 Mezzanine  -> Lobby, 113 Mezz   -> Lobby

The SIDES are unambiguous: a stair open along its length to a double-height
lobby has a guardrail there whichever way the flight runs, so those are taken
wherever the far side spans storeys or is a mezzanine.  (The side onto 108
Conference is not -- an ordinary room on one storey, so an ordinary wall.)

The ENDS are not derivable at all.  You step onto the flight at the bottom and
off it at the top, and those are opposite ends, so on each storey exactly one
end is open and the other is the wall behind the flight.  Which one is drawn as
a direction arrow, and the exported plan carries no arrows.  So the ends are
listed and left alone; --open-surface names the ones you have decided are
open, which keeps the decision in the command rather than in a hand edit.

Labelling the room "Open Stair" is the entire opt-in.  A plain "Stair" is
assumed enclosed, which is the safe reading -- a fire-rated stair with a
self-closing door is the common case, and an air boundary there would be wrong
in a way the results would not obviously show.


The engineer's overrides
------------------------

Two things a floor plan does not record, and no rule can therefore reach:

    --open-surface   these interior surfaces are open, whatever the rules say
    --solid-surface  these are real construction, overriding any rule

--solid-surface is for a wall the geometry cannot distinguish from a guardrail
because the difference is its fire rating: 205 Mezzanine reads as an open edge
onto the lobby and onto 101c, and is in fact a rated separation.
--open-surface is for the opposite -- a stair end, a doorway held open by
design.  Both are matched on either face, since an air boundary is a property
of the pair and half of one would mean nothing.

A promoted surface joins the construction already covering its space pair
rather than starting a second one.  That is not tidiness: EnergyPlus creates
mixing per Construction:AirBoundary, so two constructions between one pair of
zones would double the flow, and nothing in the model or the results would say
so.  There is a test for it.

Both are held by surface NAME, and surface names belong to OpenStudio, not to
this bridge -- nothing here ever calls setName on a surface.  A full rebuild
therefore reassigns them all, and a few land differently every time: two builds
of the BYTE-IDENTICAL floorplan JSON differed on 8 of 314 names, and one of
those, Surface 263, was a stair opening in one build and an office/store
partition in the other.  The churn sits in the fragments intersectSurfaces
makes when it splits a wall; most names are stable, which is what makes this
dangerous rather than obvious.

So re-read both lists off the report after a full build_osm_geometry.py, and do
not assume unchanged input gives unchanged names.  update_osm_geometry.py
--apply is safe: it rebuilds only the spaces whose vertex hash moved, and
nudging one vertex of 102 Office changed 5 surfaces, every one keeping its
space, its partner and its name.

Forgetting to re-read them is not hypothetical, and it fails silently: after
the roof rebuild the 205 Mezzanine report was regenerated without
--solid-surface, rule 2 duly proposed the rated wall onto the lobby and onto
101c as guardrail edges, and applying the report opened 20.3 m2 of fire
separation.  Nothing in the model objected.  The backstop is
tests/test_air_boundary_sizing.py, whose applied-model checks assert that wall
is still solid -- keyed on the space pair, so a renumbering cannot make the
check quietly pass by pointing it at different geometry.  Run the suite after
applying a report.

Keyed on the single surface, deliberately, rather than on the space pair.  A
pair can share many surfaces -- 113 Mezzanine to the lobby has six -- and they
need not all be the same kind of thing; and naming one surface asks less of the
engineer than working out what it is matched to.
"""

