# Rooms whose shared wall with a multi-story space is a guardrail.  Matched
# against the room name from the floor plan, case-insensitively.
MEZZANINE_PATTERN = r"mezzanine|balcony|gallery|catwalk"

# Rooms whose cross-section is an opening rather than a wall.  Matched against
# the room name from the floor plan, case-insensitively.
CORRIDOR_PATTERN = r"corridor|hallway|\bhall\b|passage|circulation|breezeway"

# Used only to decide which selected pairs get called out for review, never to
# select or reject one.  A corridor ending in a lobby or another corridor is an
# unambiguous open transition; one ending in an office is not, and no geometry
# distinguishes the two.
OPEN_SPACE_PATTERN = r"lobby|atrium|vestibule|concourse|open\s*(work|plan|office)"

# A stair the engineer has declared open.  A plain "Stair" gets nothing from
# rule 4: a stair is a quasi-corridor with an opening at ONE end per storey and
# a wall at the other, and which end is which is drawn as an arrow the bridge
# cannot read.  Labelling it "Open Stair" opts its *sides* in; the ends stay
# the engineer's call.
OPEN_STAIR_PATTERN = r"open\s*stair"

# A wall no wider than a quarter of the corridor's run counts as "narrow in
# comparison to the length of the hallway".
DEFAULT_CORRIDOR_NARROW_RATIO = 0.25
# It must also span the corridor's own width, within this fraction, to be a
# slice through the corridor rather than a fragment of its side.
DEFAULT_CORRIDOR_SPAN_TOL = 0.15
# And stand square to the run: |cos| between the wall's plan direction and the
# corridor's long axis, so 0.30 allows about 17 degrees out of square.
DEFAULT_CORRIDOR_SQUARE_COS = 0.30

G = 9.80665                 # m/s2
# dT across an *open* boundary is self-limiting, not a free parameter: the
# exchange this file computes is the mechanism that holds the two zones
# together, so they equilibrate. 0.5 K is the accepted working figure. A large
# dT and an open boundary are mutually exclusive -- 10 K between adjacent
# commercial zones means an enclosure (cold store, sauna), which would not have
# an open boundary at all. --delta-t exists for an engineer's judgement on a
# genuine edge case, not for exploring a range.
DEFAULT_DELTA_T = 0.5       # K, temperature difference across the opening
DEFAULT_T_MEAN = 293.15     # K, mean absolute air temperature
# IEA Annex 20 Subtask 2 (van der Maas 1992) measured 0.43 from steady-state
# doorway experiments, "in agreement with reference experiments used by
# ASHRAE"; the reported spread across studies is 0.35-0.63.  The textbook 0.6
# sits at the top of that and its own Fig. 2.18 notes "measured doorway
# velocities in air were generally smaller than the calculated parabolic
# profile using a discharge coefficient of 0.6".
CD_VERTICAL = 0.43          # discharge coefficient, measured
C_HORIZONTAL = 0.055        # Epstein thin-partition coefficient, L/D < 0.15

# Annex 20 Fig. 2.16: Scott et al. had to shrink the aperture width ratio
# below Aw = 0.1 to "block" the boundary-layer flow and drive the two zones to
# different temperatures at all.  Above it the flow is boundary-layer driven,
# not bulk-density driven -- the regime Brown & Solvason describes -- and the
# isothermality factor dT/dTw collapses towards zero.  Past this ratio the
# correlation below is extrapolation, and the report says so.
AW_DENSITY_DRIVEN_MAX = 0.1

# EnergyPlus's own default, for comparison in the report.
EPLUS_DEFAULT_ACH = 0.5

# An air boundary has to do two jobs, and they pull in opposite directions:
# couple the zones at steady state, AND stay loose enough that a transient can
# briefly override the coupling and be visible in the results.  The sized rate
# does the first well and the second not at all -- at 45 ACH a solar gain
# landing on a mezzanine is absorbed into the space below within the timestep
# and never appears.  That excursion cannot be computed in advance; it is what
# the simulation is for.  So the rate is capped to leave room for it.
#
# 5 ACH still couples an ordinary imbalance tightly (~100 W across a 79 m3
# mezzanine settles at 0.75 K) while letting a real excursion show.  A large
# sustained split in the results is then a finding about the design, which is
# the model earning its keep.
DEFAULT_MAX_ACH = 5.0


def load_model(path):
    loaded = openstudio.osversion.VersionTranslator().loadModel(
        openstudio.path(path))
    if not loaded.is_initialized():
        raise SystemExit("could not load %s" % path)
    return loaded.get()


def plan_index(plan):
    """{space_id: (story_spec, space_spec, built_height_m)}."""
    out = {}
    for story in plan["stories"]:
        for space in story["spaces"]:
            height = float(space.get("height_m") or story["floor_to_floor_m"])
            out[space["id"]] = (story, space, height)
    return out


def shaft_pairs(index):
    """Space-id pairs sharing a footprint across stories.

    Keyed on the vertex set rather than the ordered loop, so the same room
    traced from a different starting corner still matches -- the same key the
    exporter reports its cross-story matches on.
    """
    seen = {}
    for space_id, (story, space, _h) in index.items():
        key = tuple(sorted(tuple(v) for v in space["vertices"]))
        seen.setdefault(key, []).append((story["name"], space_id))

    pairs = []
    for group in seen.values():
        if len(group) < 2:
            continue
        for i in range(len(group)):
            for j in range(i + 1, len(group)):
                if group[i][0] != group[j][0]:      # different stories only
                    pairs.append((group[i][1], group[j][1]))
    return pairs


def convex_hull(points):
    """Monotone-chain hull of (x, y) tuples."""
    pts = sorted(set(points))
    if len(pts) < 3:
        return pts

    def half(seq):
        out = []
        for p in seq:
            while len(out) >= 2:
                (ax, ay), (bx, by) = out[-2], out[-1]
                if (bx - ax) * (p[1] - ay) - (by - ay) * (p[0] - ax) <= 0:
                    out.pop()
                else:
                    break
            out.append(p)
        return out

    return half(pts)[:-1] + half(pts[::-1])[:-1]


def footprint_axes(vertices):
    """(length, width, unit long axis) of the minimum-area bounding rectangle.

    A corridor's length has to survive the building not being axis-aligned --
    this one is drawn on a 45 degree north axis -- so it is measured on the
    footprint's own principal axes rather than on x and y.  The minimum-area
    rectangle is exact for the rectangular corridors this rule is about, and
    degrades sensibly for an L-shaped one.
    """
    hull = convex_hull([(round(v[0], 6), round(v[1], 6)) for v in vertices])
    best = None
    for i in range(len(hull)):
        ax, ay = hull[i]
        bx, by = hull[(i + 1) % len(hull)]
        norm = math.hypot(bx - ax, by - ay)
        if norm < 1e-9:
            continue
        ux, uy = (bx - ax) / norm, (by - ay) / norm
        along = [p[0] * ux + p[1] * uy for p in hull]
        across = [-p[0] * uy + p[1] * ux for p in hull]
        a = max(along) - min(along)
        b = max(across) - min(across)
        if best is not None and a * b >= best[0]:
            continue
        best = ((a * b, a, b, (ux, uy)) if a >= b
                else (a * b, b, a, (-uy, ux)))
    if best is None:
        return 0.0, 0.0, (1.0, 0.0)
    return best[1], best[2], best[3]


def wall_plan_run(surface):
    """(width, unit plan direction) of a vertical surface, seen from above.

    The direction comes off the bounding box, so its sign is arbitrary -- which
    is harmless here, because it is only ever used inside an absolute value.
    """
    xs = [p.x() for p in surface.vertices()]
    ys = [p.y() for p in surface.vertices()]
    dx, dy = max(xs) - min(xs), max(ys) - min(ys)
    run = math.hypot(dx, dy)
    if run < 1e-9:
        return 0.0, (1.0, 0.0)
    return run, (dx / run, dy / run)


def plane_key(surface):
    """Canonical (nx, ny, offset) of a vertical surface's line in plan.

    Sign-normalised, so two walls lying in one plane key the same whichever
    way they face -- the surfaces being compared belong to different spaces
    (a corridor's two ends, a stair's two storeys) and their outward normals
    need not agree.
    """
    normal = surface.outwardNormal()
    nx, ny = normal.x(), normal.y()
    norm = math.hypot(nx, ny)
    if norm < 1e-9:                     # horizontal: no plan line
        return None
    nx, ny = nx / norm, ny / norm
    if nx < -1e-9 or (abs(nx) <= 1e-9 and ny < 0):
        nx, ny = -nx, -ny
    pts = surface.vertices()
    offset = sum(p.x() * nx + p.y() * ny for p in pts) / len(pts)
    return (round(nx, 3), round(ny, 3), round(offset, 3))


def surface_height(surface):
    """Vertical extent of a surface, metres."""
    zs = [p.z() for p in surface.vertices()]
    return max(zs) - min(zs)


def vertical_flow(width, height, delta_t, t_mean):
    """One-way buoyancy exchange through a vertical opening, m3/s."""
    if width <= 0 or height <= 0:
        return 0.0
    return ((CD_VERTICAL / 3.0) * width * height ** 1.5
            * math.sqrt(G * delta_t / t_mean))


def horizontal_flow(area, delta_t, t_mean):
    """One-way buoyancy exchange through a horizontal opening, m3/s."""
    if area <= 0:
        return 0.0
    diameter = math.sqrt(4.0 * area / math.pi)
    return C_HORIZONTAL * math.sqrt((G * delta_t / t_mean) * diameter ** 5)


def find(model, plan, fcmap, pattern, corridor=None, open_stair=None,
         declared=None):
    """Openings needing an air boundary, as flat records.

    `corridor` is the rule-3 configuration -- pattern, narrow_ratio, span_tol,
    square_cos, exclude -- and `open_stair` the rule-4 one; either may be None
    to skip that rule.  Returns the openings, warnings, room numbers, and an
    `attention` dict of things a threshold cannot settle.
    """
    index = plan_index(plan)
    spaces = {s.nameString(): s for s in model.getSpaces()}
    room_number = {}
    for space_id, entry in fcmap.items():
        room_number[entry["space_name"]] = entry.get("room_number") or ""

    def named(space_id):
        entry = fcmap.get(space_id)
        return spaces.get(entry["space_name"]) if entry else None

    openings, warnings = [], []

    # --- rule 1: shafts -----------------------------------------------------
    for lower_id, upper_id in shaft_pairs(index):
        a, b = named(lower_id), named(upper_id)
        if a is None or b is None:
            continue
        if index[lower_id][0]["elevation_m"] > index[upper_id][0]["elevation_m"]:
            a, b = b, a
        hits = 0
        for surface in a.surfaces():
            if surface.surfaceType() not in ("Floor", "RoofCeiling"):
                continue
            adjacent = surface.adjacentSurface()
            if not adjacent.is_initialized():
                continue
            partner = adjacent.get()
            space = partner.space()
            if not space.is_initialized():
                continue
            if space.get().nameString() != b.nameString():
                continue
            openings.append({
                "kind": "shaft",
                "orientation": "horizontal",
                "space_a": a.nameString(), "space_b": b.nameString(),
                "surface_a": surface.nameString(),
                "surface_b": partner.nameString(),
                "area_m2": surface.grossArea(),
                "height_m": None,
            })
            hits += 1
        if not hits:
            warnings.append(
                "%s / %s share a footprint but no interior floor-ceiling pair "
                "joins them -- are they stacked?"
                % (a.nameString(), b.nameString()))

    # --- rule 2: mezzanine edges -------------------------------------------
    tall = set()
    for space_id, (story, _space, height) in index.items():
        if height > story["floor_to_floor_m"] + 1e-6:
            entry = fcmap.get(space_id)
            if entry:
                tall.add(entry["space_name"])

    for space_id, (_story, space, _h) in index.items():
        if not pattern.search(space["name"]):
            continue
        mezz = named(space_id)
        if mezz is None:
            continue
        for surface in mezz.surfaces():
            if surface.surfaceType() != "Wall":
                continue
            adjacent = surface.adjacentSurface()
            if not adjacent.is_initialized():
                continue
            partner = adjacent.get()
            other = partner.space()
            if not other.is_initialized():
                continue
            other_name = other.get().nameString()
            if other_name not in tall:
                continue
            openings.append({
                "kind": "mezzanine",
                "orientation": "vertical",
                "space_a": mezz.nameString(), "space_b": other_name,
                "surface_a": surface.nameString(),
                "surface_b": partner.nameString(),
                "area_m2": surface.grossArea(),
                "height_m": surface_height(surface),
            })

    # --- rule 3: corridor cross-sections -----------------------------------
    attention = {"corridor_rejected": [], "open_stair_ends": [],
                 "declared_open": [], "declared_solid": []}
    if corridor:
        found, rejected = corridor_openings(index, fcmap, named, openings,
                                            corridor)
        openings += found
        attention["corridor_rejected"] = rejected

    # --- rule 4: open stair edges ------------------------------------------
    if open_stair:
        found, ends = open_stair_openings(index, fcmap, named, openings, tall,
                                          pattern, open_stair)
        openings += found
        attention["open_stair_ends"] = ends

    # --- the engineer's overrides, last, so they beat every rule ------------
    declared = declared or {}
    if declared.get("open"):
        found, problems = promote_declared(model, openings, declared["open"])
        openings += found
        attention["declared_open"] = found
        warnings += problems
        # An end promoted by name is no longer an open question.
        promoted = {op["surface_a"] for op in found}
        attention["open_stair_ends"] = [
            op for op in attention["open_stair_ends"]
            if op["surface_a"] not in promoted]
    if declared.get("solid"):
        openings, dropped = drop_solid(openings, declared["solid"])
        attention["declared_solid"] = dropped
        named_solid = {op["surface_a"] for op in dropped}
        named_solid |= {op["surface_b"] for op in dropped}
        for missing in sorted(declared["solid"] - named_solid):
            warnings.append("--solid-surface %s: no rule had selected it, so "
                            "nothing changed" % missing)

    return openings, warnings, room_number, attention


def story_lookup(fcmap):
    """{openstudio space name: story name}."""
    return {e["space_name"]: e.get("story", "") for e in fcmap.values()}


def claimed_surfaces(openings):
    """Surfaces an earlier rule has already taken -- one surface, one
    construction."""
    claimed = set()
    for op in openings:
        claimed.add(op["surface_a"])
        claimed.add(op["surface_b"])
    return claimed


def reject_stacked_cross_sections(candidates, story_of):
    """Split cross-sections into (kept, rejected) on the two-storey test.

    Two openings that lie in the SAME plane, both cutting across the run, and
    open to rooms on DIFFERENT storeys cannot both be open: something has to
    stop a person walking out of the upper room into the void.  In real
    construction the upper one is a guardrail over a wall below, or there is
    no upper opening at all -- either way it is a special case, so both are
    rejected and reported rather than guessed at.

    Note this applies only ACROSS the run.  A long side open at two storeys is
    just a double-height edge and is perfectly ordinary; rule 4 relies on that.
    """
    planes = {}
    for cand in candidates:
        planes.setdefault(cand["plane"], []).append(cand)

    kept, rejected = [], []
    for group in planes.values():
        stories = {story_of.get(c["space_b"], "") for c in group}
        if len(group) > 1 and len(stories) > 1:
            rejected.extend(group)
        else:
            kept.extend(group)
    return kept, rejected


def corridor_openings(index, fcmap, named, claimed_by, cfg):
    """Walls that slice a corridor square across its run.

    Three conditions, all necessary -- see "Corridors" in the module docstring
    for the measurements that show why the first alone is not enough:

      narrow  the wall is short compared with the corridor's length;
      span    it covers the corridor's own width, so it is a full cross-section
              and not a fragment of the flank;
      square  it stands across the run rather than along it.
    """
    open_pattern = re.compile(OPEN_SPACE_PATTERN, re.IGNORECASE)
    room_name = {}
    for space_id, (_story, space, _h) in index.items():
        entry = fcmap.get(space_id)
        if entry:
            room_name[entry["space_name"]] = space["name"]
    story_of = story_lookup(fcmap)

    # Rules 1 and 2 have first claim: a mezzanine edge that happens to sit
    # across a corridor is already sized as a guardrail, and one surface can
    # only carry one construction.
    claimed = claimed_surfaces(claimed_by)

    found, rejected = [], []
    for space_id, (_story, space, _h) in index.items():
        if not cfg["pattern"].search(space["name"]):
            continue
        corridor = named(space_id)
        if corridor is None:
            continue
        length, width, axis = footprint_axes(space["vertices"])
        if length <= 0 or width <= 0:
            continue

        candidates = []
        for surface in corridor.surfaces():
            if surface.surfaceType() != "Wall":
                continue
            adjacent = surface.adjacentSurface()
            if not adjacent.is_initialized():
                continue
            partner = adjacent.get()
            other = partner.space()
            if not other.is_initialized():
                continue
            if surface.nameString() in claimed or partner.nameString() in claimed:
                continue

            run, direction = wall_plan_run(surface)
            if run <= 0:
                continue
            narrow = run / length
            span = run / width
            square = abs(direction[0] * axis[0] + direction[1] * axis[1])
            if (narrow > cfg["narrow_ratio"]
                    or abs(span - 1.0) > cfg["span_tol"]
                    or square > cfg["square_cos"]):
                continue

            other_name = other.get().nameString()
            if cfg["exclude"] and cfg["exclude"].search(
                    "%s|%s" % (corridor.nameString(), other_name)):
                continue

            far = room_name.get(other_name, "")
            candidates.append({
                "kind": "corridor",
                "orientation": "vertical",
                "space_a": corridor.nameString(), "space_b": other_name,
                "surface_a": surface.nameString(),
                "surface_b": partner.nameString(),
                "area_m2": surface.grossArea(),
                "height_m": surface_height(surface),
                "narrow_ratio": narrow,
                "span_ratio": span,
                "plane": plane_key(surface),
                "z_range": (min(p.z() for p in surface.vertices()),
                            max(p.z() for p in surface.vertices())),
                # False means the far side is an enclosed room, so the wall may
                # be a real one. The geometry cannot tell; the report asks.
                "partner_open": bool(cfg["pattern"].search(far)
                                     or open_pattern.search(far)),
            })
            # Claim as we go, so the same pair is not re-found from the other
            # corridor of an L-junction.  Rejected candidates are claimed too:
            # a surface this rule has ruled out must stay ruled out.
            claimed.add(surface.nameString())
            claimed.add(partner.nameString())

        kept, dropped = reject_stacked_cross_sections(candidates, story_of)
        found.extend(kept)
        rejected.extend(dropped)

    return found, rejected


def open_stair_openings(index, fcmap, named, claimed_by, tall, mezz_pattern,
                        cfg):
    """Guardrail edges of a stair the engineer has labelled open.

    A stair is a corridor stood on end, and it inherits the corridor problem in
    a sharper form: on each storey exactly one end is the way in and the other
    is the wall behind the flight, and which is which is drawn as a direction
    arrow that the exported plan does not carry.  So the two are split:

      * the SIDES -- walls along the run, onto a space that spans storeys or
        onto a mezzanine -- are guardrail edges, and are taken automatically;
      * the ENDS -- walls across the run -- are reported and left alone.

    Labelling the room "Open Stair" is the whole opt-in.  A plain "Stair" is
    assumed enclosed, which is the safe reading: a fire-rated stair with a
    self-closing door is the common case, and an air boundary there would be
    wrong in a way the results would not obviously show.
    """
    claimed = claimed_surfaces(claimed_by)
    story_of = story_lookup(fcmap)
    room_name = {}
    for space_id, (_story, space, _h) in index.items():
        entry = fcmap.get(space_id)
        if entry:
            room_name[entry["space_name"]] = space["name"]

    found, ends = [], []
    for space_id, (_story, space, _h) in index.items():
        if not cfg["pattern"].search(space["name"]):
            continue
        stair = named(space_id)
        if stair is None:
            continue
        length, width, axis = footprint_axes(space["vertices"])
        if length <= 0 or width <= 0:
            continue

        for surface in stair.surfaces():
            if surface.surfaceType() != "Wall":
                continue
            adjacent = surface.adjacentSurface()
            if not adjacent.is_initialized():
                continue
            partner = adjacent.get()
            other = partner.space()
            if not other.is_initialized():
                continue
            if surface.nameString() in claimed or partner.nameString() in claimed:
                continue

            other_name = other.get().nameString()
            far = room_name.get(other_name, "")
            # The two things an open stair can legitimately open onto.
            if not (other_name in tall or mezz_pattern.search(far)):
                continue

            run, direction = wall_plan_run(surface)
            if run <= 0:
                continue
            square = abs(direction[0] * axis[0] + direction[1] * axis[1])
            across = (abs(run / width - 1.0) <= cfg["span_tol"]
                      and square <= cfg["square_cos"])

            record = {
                "kind": "open_stair",
                "orientation": "vertical",
                "space_a": stair.nameString(), "space_b": other_name,
                "surface_a": surface.nameString(),
                "surface_b": partner.nameString(),
                "area_m2": surface.grossArea(),
                "height_m": surface_height(surface),
                "plane": plane_key(surface),
                "run_m": run,
                "partner_story": story_of.get(other_name, ""),
            }
            if across:
                # One end per storey is the way in and the other is a wall.
                # Nothing in the plan says which, so neither is taken here --
                # --open-surface promotes the ones you decide are open.
                ends.append(record)
                continue
            found.append(record)
            claimed.add(surface.nameString())
            claimed.add(partner.nameString())

    return found, ends


def promote_declared(model, openings, names):
    """Interior surfaces the engineer has declared open, whatever the rules say.

    Some openings are not derivable from a floor plan at all -- which end of a
    stair the flight arrives at, a doorway held open by design.  This is where
    that judgement is recorded so the run reproduces.

    A promoted surface joins the construction of any opening already covering
    the same pair of spaces, rather than making a second one.  Two air-boundary
    constructions between one pair of zones would give EnergyPlus two mixing
    objects and double the flow, so this is not a cosmetic detail.
    """
    by_name = {s.nameString(): s for s in model.getSurfaces()}
    claimed = claimed_surfaces(openings)
    # Existing pair -> how an opening between those two spaces is labelled.
    existing = {}
    for op in openings:
        existing.setdefault(frozenset((op["space_a"], op["space_b"])),
                            (op["kind"], op["space_a"], op["space_b"]))

    found, problems = [], []
    for name in sorted(names):
        surface = by_name.get(name)
        if surface is None:
            problems.append("--open-surface %s: no such surface" % name)
            continue
        if name in claimed:
            continue                    # a rule already took it
        adjacent = surface.adjacentSurface()
        if not adjacent.is_initialized():
            problems.append("--open-surface %s: not an interior surface "
                            "(boundary %s)"
                            % (name, surface.outsideBoundaryCondition()))
            continue
        partner = adjacent.get()
        if not (surface.space().is_initialized()
                and partner.space().is_initialized()):
            continue
        mine = surface.space().get().nameString()
        theirs = partner.space().get().nameString()
        pair = frozenset((mine, theirs))
        kind, space_a, space_b = existing.get(pair, ("declared", mine, theirs))
        # Two declared surfaces can share a pair neither rule nor an earlier
        # declaration already covers -- the second one has to see the first's
        # choice of kind/space_a/space_b, or it mints its own and group_pairs
        # (keyed on that exact triple) gives the pair two constructions.
        existing.setdefault(pair, (kind, space_a, space_b))
        vertical = surface.surfaceType() == "Wall"
        found.append({
            "kind": kind,
            "orientation": "vertical" if vertical else "horizontal",
            "space_a": space_a, "space_b": space_b,
            "surface_a": surface.nameString(),
            "surface_b": partner.nameString(),
            "area_m2": surface.grossArea(),
            "height_m": surface_height(surface) if vertical else None,
            "declared": True,
        })
        claimed.add(name)
        claimed.add(partner.nameString())
    return found, problems


def drop_solid(openings, names):
    """Openings the engineer has declared solid -- a fire wall, a rated
    separation.

    Matched on either face, so naming one side is enough: an air boundary is a
    property of the pair, and half of one would be meaningless.
    """
    kept, dropped = [], []
    for op in openings:
        if op["surface_a"] in names or op["surface_b"] in names:
            dropped.append(op)
        else:
            kept.append(op)
    return kept, dropped


def group_pairs(model, openings, room_number, delta_t, t_mean):
    """Openings collapsed to one entry per space pair, with a sized ACH."""
    volume = {s.nameString(): s.volume() for s in model.getSpaces()}
    story_of = {
        s.nameString(): (s.buildingStory().get().nameString()
                         if s.buildingStory().is_initialized() else "")
        for s in model.getSpaces()}
    wall_areas = {
        s.nameString(): sum(f.grossArea() for f in s.surfaces()
                            if f.surfaceType() == "Wall")
        for s in model.getSpaces()}

    groups = {}
    for op in openings:
        key = (op["kind"], op["space_a"], op["space_b"])
        groups.setdefault(key, []).append(op)

    results = []
    for (kind, space_a, space_b), ops in groups.items():
        flow = 0.0
        for op in ops:
            if op["orientation"] == "vertical":
                height = op["height_m"] or 0.0
                # Effective width, so a non-rectangular opening still gets its
                # true area at its true height.
                width = op["area_m2"] / height if height > 0 else 0.0
                flow += vertical_flow(width, height, delta_t, t_mean)
            else:
                flow += horizontal_flow(op["area_m2"], delta_t, t_mean)

        v_a, v_b = volume.get(space_a, 0.0), volume.get(space_b, 0.0)
        v_small = min(v_a, v_b)

        # Annex 20's aperture width ratio, Aw = W / Wr: how much of the
        # smaller zone's perimeter is open.  Areas divided by a common height
        # give the same ratio as widths, so this is Aw directly.
        smaller = space_a if v_a <= v_b else space_b
        wall_area = wall_areas.get(smaller, 0.0)
        aw = (sum(o["area_m2"] for o in ops) / wall_area) if wall_area else 0.0
        ach = (flow * 3600.0 / v_small) if v_small > 0 else 0.0

        num_a = room_number.get(space_a, "") or space_a
        num_b = room_number.get(space_b, "") or space_b
        if kind == "shaft":
            label = num_a if num_a == num_b else "%s-%s" % (num_a, num_b)
            name = "Air Boundary - Shaft %s" % label
        elif kind == "corridor":
            name = "Air Boundary - Corridor %s to %s" % (num_a, num_b)
        elif kind == "open_stair":
            name = "Air Boundary - Open Stair %s to %s" % (num_a, num_b)
        elif kind == "declared":
            label = num_a if num_a == num_b else "%s to %s" % (num_a, num_b)
            name = "Air Boundary - Opening %s" % label
        else:
            name = "Air Boundary - Mezzanine %s to %s" % (num_a, num_b)

        area = sum(o["area_m2"] for o in ops)
        results.append({
            "construction_name": name,
            # Half the opening carries flow each way, so this is the mean
            # interfacial speed -- the quickest check that a rate is sane.
            "velocity_m_s": (flow / (area / 2.0)) if area > 0 else 0.0,
            "kind": kind,
            "space_a": space_a, "space_b": space_b,
            "openings": len(ops),
            "area_m2": area,
            "flow_m3_s": flow,
            "volume_smaller_m3": v_small,
            "smaller_space": smaller,
            "aperture_width_ratio": aw,
            # Rule 3 only. False = the far side is an enclosed room, so the
            # report asks the engineer to confirm this is really an opening.
            "partner_open": all(o.get("partner_open", True) for o in ops),
            "narrow_ratio": max([o["narrow_ratio"] for o in ops]
                                if kind == "corridor" else [0.0]),
            "span_ratio": max([o["span_ratio"] for o in ops]
                              if kind == "corridor" else [0.0]),
            # A fixed ZoneMixing rate is linear in dT, unlike the buoyancy it
            # stands in for, so the dT a 1 kW imbalance produces is simply
            # W / (rho.cp.Q) -- and it rises in proportion to any cap applied.
            "delta_t_at_1kw": (1000.0 / (1.2 * 1006.0 * flow)) if flow else 0.0,
            "recommended_ach": ach,
            "surface_names": sorted(
                [o["surface_a"] for o in ops] + [o["surface_b"] for o in ops],
                key=lambda n: (re.sub(r"\d+$", "", n),
                               int(re.search(r"\d+$", n).group())
                               if re.search(r"\d+$", n) else 0)),
        })

    # Room numbers are not unique across stories -- a stair is "101d" on both
    # -- so two genuinely different space pairs can land on one construction
    # name.  Applying both would silently merge them into one construction, so
    # collisions are broken by the story of the first space.
    counts = {}
    for r in results:
        counts[r["construction_name"]] = counts.get(r["construction_name"],
                                                    0) + 1
    for r in results:
        if counts[r["construction_name"]] > 1:
            story = story_of.get(r["space_a"], "")
            if story:
                r["construction_name"] = "%s - %s" % (r["construction_name"],
                                                      story)
    seen = {}
    for r in results:
        name = r["construction_name"]
        if name in seen:
            seen[name] += 1
            r["construction_name"] = "%s %d" % (name, seen[name])
        else:
            seen[name] = 1

    results.sort(key=lambda r: (r["kind"], -r["recommended_ach"]))
    return results


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("osm")
    ap.add_argument("floorplan")
    ap.add_argument("--fcmap", help="defaults to <osm>.fcmap.json")
